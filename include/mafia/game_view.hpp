#pragma once

#include <vector>

#include "mafia/player.hpp"
#include "mafia/shared_ptr.hpp"

namespace mafia {

class InputBroker;  // полное определение в coroutines.hpp

// Read-only снимок игры, который Ведущий передаёт игроку в момент его хода.
// Игрок не имеет прямого доступа к GameMaster или к другим игрокам напрямую —
// он видит только то, что разрешено содержимым GameView, и возвращает своё
// решение через act()/vote(), а не выполняет его сам.
//
// Пока здесь минимум — список живых игроков и номер раунда. Позже, когда
// появятся Ведущий и лог игры, сюда естественно добавится история раундов
// (нужна, например, ИИ-агенту и Комиссару, помнящему свои прошлые проверки).
struct GameView {
    std::vector<SharedPtr<Player>> alive_players;
    int round_number = 0;

    // Канал связи игрока-человека с консолью через Ведущего. Боты им не
    // пользуются; nullptr допустим, пока в игре нет интерактивных игроков.
    InputBroker* input = nullptr;

    // Погибшие этой ночью: заполняется только на втором этапе ночи, когда
    // ходит Реаниматор — ему сообщают имена тех, кто собирается умереть
    // (после лечения Доктора). Роли игрок по этим объектам знать не должен.
    // Казнённые голосованием сюда не попадают.
    std::vector<SharedPtr<Player>> killed_tonight;
};

}  // namespace mafia
