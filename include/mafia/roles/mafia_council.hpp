#pragma once

#include <vector>

#include "mafia/action.hpp"

namespace mafia {
struct GameView;  // полное определение в game_view.hpp; тут достаточно
                   // неполного типа — используется только как параметр по ссылке.
}  // namespace mafia

namespace mafia::roles {

// Общее состояние, которое разделяют между собой все игроки-мафиози —
// "стол переговоров банды". Всем членам банды раздаётся один и тот же
// экземпляр через SharedPtr (общие структуры данных должны храниться в
// умных указателях из п.1 задания): use_count() этого control block'а равен
// числу мафиози, которые всё ещё держат на него ссылку.
struct MafiaCouncil {
    // Кто вообще состоит в банде (включая себя). Так рядовой мафиози не
    // выберет целью своего же товарища, не подглядывая при этом в чужой
    // role()/team() через публичный интерфейс Player — это знание банды,
    // а не что-то, что вправе знать кто угодно, у кого есть SharedPtr<Player>.
    std::vector<PlayerId> members;

    // "Босс" — не хранится как мутируемое поле: вычисляется заново на каждую
    // ночь как живой член банды с наименьшим id. Если прежний Босс погиб,
    // следующий по счёту автоматически берёт слово без ручной синхронизации
    // и без риска забыть обновить поле в нужный момент. Правила описывают
    // явную передачу мандата только для опциональной роли Похититель; для
    // обязательной Мафии порядок наследования — наша собственная конвенция.
    PlayerId current_boss(const GameView& view) const;
};

}  // namespace mafia::roles
